        writer.write("  var normalized = text.replace(/\u00A0/g, ' ').replace(/,/g, '.');\n");
        writer.write("  var match = normalized.match(/-?\\d[\\d\\s]*(?:\\.\\d+)?/);\n");
        writer.write("  if (!match) return Number.NaN;\n");
        writer.write("  return Number(match[0].replace(/\s+/g, ''));\n");
        writer.write("}\n");
